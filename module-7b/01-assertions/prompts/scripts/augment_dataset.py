"""
augment_dataset.py
Reads your golden_data.csv and generates multiple paraphrase variants
per row using OpenAI, producing a larger augmented_data.csv ready for
validation.

Usage:
    python scripts/augment_dataset.py

    # Or override defaults:
    python scripts/augment_dataset.py \
        --input   data/golden_augmentation/golden_dataset.csv \
        --output  data/golden_augmentation/augmented_data.csv \
        --count   4

How it works:
    For every row in your golden dataset, OpenAI rewrites the input
    prompt in `count` different ways — varying tone, length, formality,
    and phrasing — while preserving the original intent and expected
    behavior. The original row is kept; the variants are appended.

    20 golden rows × count=4 variants = 80 augmented + 20 original = 100 total
    Plan for ~15-20% waste from cleaning → lands near 80 clean rows.

Output columns (same as golden_dataset.csv plus one addition):
    user_input, expected_behavior, category, severity, __expected__, source

    source = "original"  for rows carried over from golden_dataset.csv
    source = "augmented" for rows generated by this script
"""

