DEFAULT_COUNT  = 4   # variants per row — change to 3 for smaller datasets

MODEL = "gpt-4o"


# ── Helpers ──────────────────────────────────────────────────────────────────

def load_csv(path: str) -> list[dict]:
    with open(path, encoding="cp1252", newline="") as f:
        return list(csv.DictReader(f))


def save_csv(rows: list[dict], path: str):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)


def print_distribution(rows: list[dict], label: str):
    from collections import Counter
    dist = Counter(r.get("category", "unknown") for r in rows)
    total = len(rows)
    print(f"\n📊 {label} ({total} rows):")
    for cat in sorted(dist):
        n   = dist[cat]
        pct = n / total * 100
        bar = "█" * (n // 2)
        print(f"   {cat:<20} {bar:<25} {n:3d}  ({pct:.0f}%)")


# ── Core augmentation ────────────────────────────────────────────────────────

def build_prompt(row: dict, count: int) -> str:
    """
    Build the prompt sent to OpenAI for a single golden row.

    We ask for variations across four dimensions:
    - Formality   : formal → casual → terse
    - Length      : brief question → full sentence → multi-clause
    - Persona     : neutral → frustrated → polite
    - Phrasing    : direct → indirect → implicit

    We deliberately do NOT ask OpenAI to change the category or severity —
    those are inherited from the original row.
    """
    return f"""You are a QA expert generating test data for an LLM-powered chatbot.

Original test input:
"{row['user_input']}"

Category    : {row.get('category', 'happy_path')}
Expected    : {row.get('expected_behavior', '')}

Task: Rewrite the input {count} times. Each rewrite must:
- Keep exactly the same intent and expected behavior
- Vary at least one of: tone, length, formality, phrasing, persona
- Sound like something a real user would actually type

Good variation examples for "How do I cancel my superannuation?":
- "Cancel my superannuation"              (terse)
- "I'd like to discontinue my superannuation membership"  (formal)
- "CANCEL MY SUPERANNUATION NOW"          (frustrated, caps)
- "Is it possible to stop my superannuation?"        (indirect)

Return a JSON array of exactly {count} strings — the rewritten inputs only.
No explanations, no markdown, no extra keys. Just the array.

Example format:
["variant one", "variant two", "variant three", "variant four"]"""


def augment_row(client: OpenAI, row: dict, count: int) -> list[dict]:
    """
    Generate `count` variants for a single row.
    Returns a list of new row dicts with source="augmented".
    """
    prompt = build_prompt(row, count)

    response = client.chat.completions.create(
        model=MODEL,
        messages=[{"role": "user", "content": prompt}],
        max_tokens=4000
    )

    raw = response.choices[0].message.content.strip()

    # Strip markdown fences if OpenAI adds them
    raw = raw.replace("```json", "").replace("```", "").strip()

    variants = json.loads(raw)

    new_rows = []
    for variant in variants:
        new_row = {
            "user_input":        str(variant).strip(),
            "expected_behavior": row.get("expected_behavior", ""),
            "category":          row.get("category", "happy_path"),
            "severity":          row.get("severity", "low"),
            "__expected__":      row.get("__expected__", ""),
            "source":            "augmented",
        }
        new_rows.append(new_row)

    return new_rows


# ── Main ─────────────────────────────────────────────────────────────────────

def run(input_path: str, output_path: str, count: int):
    api_key = os.getenv("OPENAI_API_KEY")
    if not api_key:
        raise EnvironmentError(
            "OPENAI_API_KEY not set. Add it to your .env file or export it."
        )

    client = OpenAI(api_key=api_key)

    golden = load_csv(input_path)
    print(f"\n── Augment Dataset ─────────────────────────────────────────────")
    print(f"   Input  : {input_path}  ({len(golden)} rows)")
    print(f"   Output : {output_path}")
    print(f"   Count  : {count} variants per row")
    print(f"   Total  : {len(golden)} original + {len(golden) * count} augmented"
          f" = {len(golden) * (count + 1)} rows\n")

    # Mark originals so validate / topup can distinguish them
    for row in golden:
        row["source"] = "original"

    augmented = []
    failed    = []

    for i, row in enumerate(golden, 1):
        try:
            variants = augment_row(client, row, count)
            augmented.extend(variants)
            print(f"   [{i:02d}/{len(golden)}] ✅  {row['user_input'][:60]}")
        except json.JSONDecodeError as e:
            print(f"   [{i:02d}/{len(golden)}] ⚠️  JSON parse failed — skipping row")
            print(f"              {row['user_input'][:60]}")
            failed.append(row)
        except Exception as e:
            print(f"   [{i:02d}/{len(golden)}] ❌  Error: {e}")
            failed.append(row)

    all_rows = golden + augmented
    save_csv(all_rows, output_path)

    print_distribution(all_rows, "Output distribution")

    print(f"\n── Summary ─────────────────────────────────────────────────────")
    print(f"   Original rows  : {len(golden)}")
    print(f"   Augmented rows : {len(augmented)}")
    print(f"   Failed rows    : {len(failed)}")
    print(f"   Total saved    : {len(all_rows)}")
    print(f"   File           : {output_path}")

    if failed:
        print(f"\n   ⚠️  {len(failed)} rows failed to augment:")
        for r in failed:
            print(f"      - {r['user_input'][:60]}")
        print(f"      These original rows are still included in the output.")

    print(f"\n   Next step:")
    print(f"   python scripts/validate_dataset.py {output_path}\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Augment a golden test dataset using Open AI paraphrases."
    )
    parser.add_argument(
        "--input",
        default=DEFAULT_INPUT,
        help=f"Path to golden CSV (default: {DEFAULT_INPUT})"
    )
    parser.add_argument(
        "--output",
        default=DEFAULT_OUTPUT,
        help=f"Path to write augmented CSV (default: {DEFAULT_OUTPUT})"
    )
    parser.add_argument(
        "--count",
        type=int,
        default=DEFAULT_COUNT,
        help=f"Number of variants per row (default: {DEFAULT_COUNT})"
    )
    args = parser.parse_args()

    if not Path(args.input).exists():
        print(f"❌  Input file not found: {args.input}")
        exit(1)

    run(args.input, args.output, args.count)
